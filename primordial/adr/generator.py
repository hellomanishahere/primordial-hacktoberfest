"""ADR and MADR (Markdown Any Decision Record) generator."""
from __future__ import annotations

from typing import Optional
from primordial.models import DecisionRecord, Discussion


def generate_madr(decision: DecisionRecord, discussion: Optional[Discussion] = None) -> str:
    """Generate Markdown Any Decision Record (MADR 3.0.0 compliant)."""
    participants_str = ", ".join(f"@{p}" for p in discussion.get_all_participants()) if discussion else "Engineering Team"
    source_url = discussion.source_url if discussion else ""
    source_title = discussion.title if discussion else decision.title

    lines = [
        f"# {decision.title}",
        "",
        f"* Status: **{decision.status}**",
        f"* Date: {decision.date}",
        f"* Deciders: {participants_str}",
    ]
    if source_url:
        lines.append(f"* Source Discussion: [{source_title}]({source_url})")

    lines.extend([
        "",
        "## Context and Problem Statement",
        "",
        decision.problem_statement,
        "",
        decision.context,
        "",
        "## Considered Options",
        "",
    ])

    for opt in decision.considered_options:
        is_chosen = opt.lower() in decision.accepted_option.lower() or decision.accepted_option.lower() in opt.lower()
        badge = " *(Chosen)*" if is_chosen else " *(Rejected)*"
        lines.append(f"* {opt}{badge}")

    lines.extend([
        "",
        "## Decision Outcome",
        "",
        f"Chosen option: **{decision.accepted_option}**, because:",
        f"{decision.decision_outcome}",
        "",
        "### Positive Consequences",
        "",
    ])

    for pos in decision.consequences_positive:
        lines.append(f"* {pos}")

    if decision.consequences_negative:
        lines.extend([
            "",
            "### Negative Consequences (Trade-offs)",
            "",
        ])
        for neg in decision.consequences_negative:
            lines.append(f"* {neg}")

    # Detailed Section: Rejected Alternatives & Grounded Objections
    if decision.rejected_alternatives:
        lines.extend([
            "",
            "## Pros and Cons of Rejected Options",
            "",
        ])
        for ra in decision.rejected_alternatives:
            lines.append(f"### {ra.name}")
            lines.append(f"* Proposed by: @{ra.proposer}")
            lines.append("* Rejection reasons:")
            for reason in ra.rejection_reasons:
                lines.append(f"  * ❌ {reason}")
            if ra.key_objection_quote:
                author_ref = f" - @{ra.objection_author}" if ra.objection_author else ""
                link_ref = f" ([Source]({ra.comment_url}))" if ra.comment_url else ""
                lines.append(f"* Key objection quote:{author_ref}{link_ref}")
                lines.append(f"  > \"{ra.key_objection_quote}\"")
            lines.append("")

    # Code Grounding Section
    if decision.affected_components:
        lines.extend([
            "## Code Grounding & Impacted Components",
            "",
            "The following files, modules, and directories are bound to this decision:",
            "",
        ])
        for comp in decision.affected_components:
            lines.append(f"* `{comp}`")
        lines.append("")

    # Verified Evidence Section
    if decision.evidence_quotes:
        lines.extend([
            "## Verified Evidence Citations",
            "",
            "| ID | Quote | Author | Verified | Source |",
            "|---|---|---|:---:|---|",
        ])
        for eq in decision.evidence_quotes:
            status = "✅ Verified" if eq.verified else "⚠️ Approximate"
            author_str = f"@{eq.author}" if eq.author else "contributor"
            link_str = f"[Comment {eq.comment_id}]({eq.comment_url})" if eq.comment_url else eq.comment_id
            quote_clean = eq.quote.replace("\n", " ").replace("|", "\\|")
            lines.append(f"| {eq.id} | \"{quote_clean}\" | {author_str} | {status} | {link_str} |")
        lines.append("")

    lines.extend([
        "---",
        "*Generated by PRIMORDIAL Decision Intelligence Platform — Hacktoberfest 2026*",
    ])

    return "\n".join(lines)
